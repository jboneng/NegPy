@dataclass(frozen=True)
class Model7400:
    name: str = "plustek-opticfilm-7400-v2"
    vendor: str = "PLUSTEK"
    model: str = "OpticFilm 7400"
    asic: str = "GL845"
    usb_vendor_id: int = 0x07B3
    usb_product_id: int = 0x0C3A
    #: Locked out until live-validated in a future release (SANE tables only).
    scan_ready: bool = False
    resolutions_dpi: tuple[int, ...] = (7200, 3600, 2400, 1200, 600)
    bpp_gray: tuple[int, ...] = (16,)
    bpp_color: tuple[int, ...] = (16,)
    supports_infrared: bool = False
    x_size_mm: float = 36.0
    y_size_mm: float = 44.0
    x_offset_ta_mm: float = 0.5
    y_offset_ta_mm: float = 29.0
    x_size_ta_mm: float = 36.33
    y_size_ta_mm: float = 25.0
    x_size_calib_mm: float = 36.83
    y_size_calib_ta_mm: float = 2.0
    y_offset_calib_white_ta_mm: float = 0.0
    y_offset_sensor_to_ta_mm: float = 0.0
    ld_shift_r: int = 0
    ld_shift_g: int = 12
    ld_shift_b: int = 24
    stagger_y_by_dpi: Mapping[int, tuple[int, ...]] = field(
        default_factory=lambda: {600: (), 1200: (), 2400: (), 3600: (), 7200: (4, 0)}
    )
    register_dpiset_by_dpi: Mapping[int, int] = field(
        default_factory=lambda: dict(_REGISTER_DPISET)
    )
    output_pixel_offset_by_dpi: Mapping[int, int] = field(
        default_factory=lambda: dict(_OUTPUT_PIXEL_OFFSET)
    )
    register_dpihw: int = 1200
    exposure_lperiod: int = 14000
    motor_base_ydpi: int = 3600
    optical_resolution: int = 7200
    motor_profile: MotorProfile = _MOTOR
    init_regs: Mapping[int, int] = field(default_factory=lambda: dict(_INIT))
    sensor_custom_regs: Mapping[int, int] = field(default_factory=lambda: dict(_SENSOR))
    frontend_regs: Mapping[int, int] = field(default_factory=lambda: dict(_FRONTEND))
    gpo_regs: Mapping[int, int] = field(default_factory=lambda: dict(_GPO))
    memory_layout_regs: Mapping[int, int] = field(default_factory=lambda: dict(_MEMORY))

    @property
    def max_area_mm(self) -> tuple[float, float]:
        return (self.x_size_ta_mm, self.y_size_ta_mm)

    def boot_register_map(self) -> dict[int, int]:
        regs = dict(self.init_regs)
        regs.update(self.sensor_custom_regs)
        regs[0x05] = (regs.get(0x05, 0) & ~0xC0) | 0x40
        return regs


